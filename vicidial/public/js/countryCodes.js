// Sort prefixes by length (longest first) so e.g. +1242 (Bahamas) matches before +1 (USA) if we add NA countries later.
countryPrefixesMap.sort((a, b) => b.prefix.length - a.prefix.length);

window.getCountryByPrefix = function(number) {
    if (!number) return 'Other 🌍';
    const numStr = String(number).replace(/[^0-9]/g, '');
    
    // Some formats might have 00 before country code
    let cleanNum = numStr;
    if (cleanNum.startsWith('00')) {
        cleanNum = cleanNum.substring(2);
    }

    for (const c of countryPrefixesMap) {
        if (cleanNum.startsWith(c.prefix)) return c.name;
    }
    return 'Other 🌍';
};
